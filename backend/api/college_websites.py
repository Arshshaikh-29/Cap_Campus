def get_college_links(college_code: str) -> Dict[str, Optional[str]]:
    code = str(college_code or "").strip()
    if code == "16006":
        code = "6006"
    elif code == "14005":
        code = "4005"
    website = COLLEGE_WEBSITES.get(code)
    domain = None
    if website:
        host = urlparse(website).netloc
        domain = host[4:] if host.startswith("www.") else host
    cet_url = CET_PORTAL_URLS.get(code)
    if not cet_url and code.isdigit():
        padded = code.zfill(5)
        cet_url = f"https://fe2025.mahacet.org/StaticPages/frmInstituteSummary.aspx?InstituteCode={padded}"
    return {
        "official_website": website,
        "website_domain": domain,
        "cet_portal_url": cet_url,
    }
