def _norm_code(college_code: str) -> str:
    c = str(college_code or "").strip()
    if c == "16006":
        return "6006"
    if c == "14005":
        return "4005"
    return c


def get_college_insights(college_code: str) -> Dict[str, Any]:
    """Full detailed placements, fees, ROI & authentic official source links for a college."""
    code = _norm_code(college_code)
    links = get_college_links(code)
    raw = VERIFIED_COLLEGE_INSIGHTS.get(code)
    official_site = links.get("official_website")
    cet_url = links.get("cet_portal_url")

    official_sources = {
        "fra_portal_url": FRA_PORTAL_URL,
        "nirf_portal_url": NIRF_PORTAL_URL,
        "mahadbt_portal_url": MAHADBT_PORTAL_URL,
        "official_website": official_site,
        "cet_portal_url": cet_url,
    }

    if not raw:
        return {
            "has_verified_insights": False,
            "placements": None,
            "fees": None,
            "roi": None,
            "concessions": MAHARASHTRA_CONCESSIONS,
            "official_sources": official_sources,
        }

    is_fra = raw["fee_source_type"] == "FRA"
    four_year_inr = int(raw["annual_open_inr"] * 4)
    median_inr = raw["nirf_median_lpa"] * 100_000
    payback_years = round(four_year_inr / median_inr, 2) if median_inr > 0 else None
    if payback_years is not None:
        if payback_years <= 0.7:
            roi_tier = "Exceptional ROI"
        elif payback_years <= 1.2:
            roi_tier = "Strong ROI"
        elif payback_years <= 1.8:
            roi_tier = "Balanced ROI"
        else:
            roi_tier = "Moderate ROI"
    else:
        roi_tier = None

    return {
        "has_verified_insights": True,
        "placements": {
            "nirf_median_lpa": raw["nirf_median_lpa"],
            "average_lpa": raw["average_lpa"],
            "highest_lpa": raw["highest_lpa"],
            "placement_rate": raw["placement_rate"],
            "top_recruiters": raw["top_recruiters"],
            "note": raw["placement_note"],
            "report_cycle": "NIRF 2024–25 Filing & Institute T&P Cell",
            "source_label": "NIRF (Ministry of Education) & Official Institute T&P Cell",
            "source_url": official_site or NIRF_PORTAL_URL,
            "nirf_portal_url": NIRF_PORTAL_URL,
        },
        "fees": {
            "institute_type": raw["institute_type"],
            "annual_open_inr": raw["annual_open_inr"],
            "fee_range_label": raw["fee_range_label"],
            "four_year_estimate_inr": four_year_inr,
            "academic_cycle": "2024–25 / 2025–26 (CAP Open Category)",
            "source_label": (
                "Fees Regulating Authority (FRA), Govt. of Maharashtra"
                if is_fra
                else "Official Institute / DTE Maharashtra Fee Circular"
            ),
            "source_url": FRA_PORTAL_URL if is_fra else (official_site or cet_url or FRA_PORTAL_URL),
            "institute_url": official_site,
            "fra_portal_url": FRA_PORTAL_URL,
            "mahadbt_portal_url": MAHADBT_PORTAL_URL,
        },
        "roi": {
            "payback_years": payback_years,
            "roi_tier": roi_tier,
            "four_year_fee_inr": four_year_inr,
            "nirf_median_lpa": raw["nirf_median_lpa"],
        },
        "concessions": MAHARASHTRA_CONCESSIONS,
        "official_sources": official_sources,
    }


